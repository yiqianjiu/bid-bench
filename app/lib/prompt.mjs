export function roleReviewUserPrompt(chapters) {
  const L = ['【投标文件章节清单】'];
  (chapters || []).forEach((c) => {
    // v1.2.0：判性质不能只看标题 —— 把章节正文的摘录一起给 AI，
    // 否则「实施」「方案」这类中性标题很容易判错，知识卡就漏了重要内容。
    const body = String(c.body || '').replace(/\s+/g, ' ').trim();
    const snip = body ? (' ｜ 正文摘录：' + body.slice(0, 260)) : '';
    const hint = c.hint ? (' ｜ 编写要点：' + String(c.hint).slice(0, 80)) : '';
    L.push('- id=' + c.id + ' ｜ 标题：' + c.title + hint + snip);
  });
  L.push('');
  L.push('请结合标题和正文摘录逐章给出 role，输出 JSON。');
  return L.join('\n');
}

export function draftUserPrompt(ctx) {
  const L = [];
  if (ctx.roleKind === 'tech') L.push('请以本项目的技术负责人（AI 技术专家）身份，为下面这一章撰写投标文件正文。');
  else if (ctx.roleKind === 'biz') L.push('请以本项目的商务负责人（AI 商务专家）身份，为下面这一章撰写投标文件正文。');
  else L.push('请为下面这一章撰写投标文件正文。');
  L.push('');
  L.push('【项目信息】');
  L.push('项目名称：' + (ctx.projectName || '—'));
  L.push('招标编号：' + (ctx.projectCode || '—'));
  L.push('招标人：' + (ctx.owner || '—'));
  L.push('采购方式：' + (ctx.method || '—'));
  L.push('预算金额：' + (ctx.budget || '—'));
  L.push('投标截止时间：' + (ctx.deadline || '—'));
  L.push('');
  L.push('【所在文件】' + (ctx.docName || '投标文件') + ' ／ 【本章标题】' + (ctx.chapterTitle || ''));
  if (ctx.roleKind === 'tech' || ctx.roleKind === 'biz') {
    L.push('【本章性质】' + (ctx.roleKind === 'tech'
      ? '重要技术内容 —— 按【AI 技术专家】身份撰写'
      : '重要商务内容 —— 按【AI 商务专家】身份撰写'));
  }
  if (ctx.profileText) {
    L.push('');
    L.push(ctx.roleKind === 'tech' ? '【项目技术专家画像（已由操作人员确认）】' : '【项目商务专家画像（已由操作人员确认）】');
    L.push(ctx.profileText);
  }
  if (ctx.referenceText) {
    L.push('');
    L.push(ctx.referenceText);
  }
  if (ctx.hint) { L.push('【本章必须覆盖的要求】'); L.push(ctx.hint); }
  if (ctx.scoreStandard) { L.push('【对应评分标准（要逐条拿到分）】'); L.push(ctx.scoreStandard); }
  if (ctx.clauses && ctx.clauses.length) {
    L.push('【招标文件原文条款 —— 下面每一条都必须在正文里有对应响应，一条都不能漏】');
    L.push('（共 ' + ctx.clauses.length + ' 条。要求：按下面的顺序写，每条先点明该条要求，再写我方的具体做法或承诺。）');
    ctx.clauses.forEach((c, i) => L.push((i + 1) + '. ' + (c.page ? '[第' + c.page + '页] ' : '') + c.text));
  } else {
    L.push('【招标文件条款】本次没有检索到与本章直接对应的条款。请你只围绕本章标题与上面给出的要求写，不要编造招标文件内容。');
  }
  if (ctx.outline && ctx.outline.length) {
    L.push('【本文件其他章节（不要重复写它们的内容）】');
    L.push(ctx.outline.slice(0, 40).join('、'));
  }
  L.push('');
  L.push('【字数要求】' + (ctx.words || 450) + ' 字左右。');
  if (ctx.mode === 'expand' && ctx.current) {
    L.push('【现在这一章已有的内容（请在此基础上扩写、细化、补足评分点，保留已有的事实与措辞，不要推倒重写）】');
    L.push(String(ctx.current).slice(0, 6000));
  }
  L.push('');
  L.push('直接输出正文。');
  return L.join('\n');
}
